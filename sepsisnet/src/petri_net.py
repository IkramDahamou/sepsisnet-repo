"""
Petri Net formal verification of the SepsisNet alert workflow.

Places:
  P_Ready         — patient event ready for analysis
  P_Alert_Gen     — alert generated by detector
  P_Notify        — notification sent to nurse
  P_Escalate      — escalated to senior physician
  P_ICU_Code      — ICU code called
  P_Resolved      — case resolved / closed
  P_Active_Alerts — concurrent active alerts (capacity = icu_capacity)

Transitions:
  T_Detect   — detection event fires an alert
  T_Notify   — alert triggers notification
  T_Escalate — notification escalates to physician
  T_Code     — escalation triggers ICU code
  T_Complete — resolution, removes from active set

Verification:
  deadlock_freedom — at least one transition enabled whenever tokens exist
  boundedness      — P_Active_Alerts never exceeds ICU capacity
"""
from __future__ import annotations

import logging
from typing import Dict, List, Optional

logger = logging.getLogger(__name__)


class Place:
    """A Petri Net place (state node) with optional capacity bound."""

    def __init__(self, name: str, capacity: Optional[int] = None) -> None:
        self.name = name
        self.tokens: int = 0
        self.capacity = capacity

    def can_add(self) -> bool:
        return self.capacity is None or self.tokens < self.capacity

    def add(self) -> bool:
        if not self.can_add():
            return False
        self.tokens += 1
        return True

    def remove(self) -> bool:
        if self.tokens <= 0:
            return False
        self.tokens -= 1
        return True

    def __repr__(self) -> str:
        cap = f"/{self.capacity}" if self.capacity is not None else ""
        return f"Place({self.name}, tokens={self.tokens}{cap})"


class Transition:
    """A Petri Net transition (event) with input and output places."""

    def __init__(
        self,
        name: str,
        inputs: List[Place],
        outputs: List[Place],
    ) -> None:
        self.name = name
        self.inputs = inputs
        self.outputs = outputs

    def is_enabled(self) -> bool:
        return (all(p.tokens > 0 for p in self.inputs) and
                all(p.can_add() for p in self.outputs))

    def fire(self) -> bool:
        if not self.is_enabled():
            return False
        for p in self.inputs:
            p.remove()
        for p in self.outputs:
            p.add()
        return True

    def __repr__(self) -> str:
        return f"Transition({self.name})"


class SepsisNetPetriNet:
    """
    Petri Net model of the SepsisNet alert escalation workflow.

    Used for formal verification:
      - deadlock_freedom : no stuck states when alerts are active
      - boundedness      : P_Active_Alerts never exceeds icu_capacity
    """

    def __init__(self, icu_capacity: int = 10) -> None:
        self.icu_capacity = icu_capacity
        self._build()

    # ------------------------------------------------------------------

    def _build(self) -> None:
        """Instantiate places and transitions."""
        self.P_Ready = Place("P_Ready")
        self.P_Alert = Place("P_Alert_Gen")
        self.P_Notify = Place("P_Notify")
        self.P_Escalate = Place("P_Escalate")
        self.P_Code = Place("P_ICU_Code")
        self.P_Resolved = Place("P_Resolved")
        self.P_Active = Place("P_Active_Alerts", capacity=self.icu_capacity)

        self.places: List[Place] = [
            self.P_Ready, self.P_Alert, self.P_Notify,
            self.P_Escalate, self.P_Code, self.P_Resolved, self.P_Active,
        ]

        self.T_Detect = Transition(
            "T_Detect", [self.P_Ready], [self.P_Alert])
        self.T_Notify = Transition(
            "T_Notify", [self.P_Alert], [self.P_Notify, self.P_Active])
        self.T_Escalate = Transition(
            "T_Escalate", [self.P_Notify], [self.P_Escalate])
        self.T_Code = Transition(
            "T_Code", [self.P_Escalate], [self.P_Code])
        self.T_Complete = Transition(
            "T_Complete", [self.P_Code, self.P_Active], [self.P_Resolved])

        self.transitions: List[Transition] = [
            self.T_Detect, self.T_Notify, self.T_Escalate,
            self.T_Code, self.T_Complete,
        ]

    def _reset(self) -> None:
        for p in self.places:
            p.tokens = 0

    # ------------------------------------------------------------------
    # Verification methods
    # ------------------------------------------------------------------

    def verify_deadlock_freedom(self) -> bool:
        """
        Check deadlock-freedom by simulating through one full alert cycle.
        Returns True if the net can always progress to P_Resolved.
        """
        self._reset()
        self.P_Ready.tokens = 1

        # Fire transitions in workflow order
        for t in self.transitions:
            if t.is_enabled():
                t.fire()

        # Deadlock-free if all tokens ended in P_Resolved (final place)
        unresolved = sum(p.tokens for p in self.places) - self.P_Resolved.tokens
        return unresolved == 0

    def verify_boundedness(self) -> bool:
        """Return True if P_Active_Alerts has a finite capacity bound."""
        return self.P_Active.capacity is not None

    # ------------------------------------------------------------------
    # Simulation
    # ------------------------------------------------------------------

    def simulate_alert_sequence(self, states: List) -> List[Dict]:
        """
        Simulate the Petri Net over a sequence of MDP alert states.

        Parameters
        ----------
        states : list of AlertState values from the MDP simulation

        Returns
        -------
        markings : list of {place_name: token_count} dicts, one per step
        """
        self._reset()
        markings: List[Dict] = []

        for state in states:
            state_val = int(state)

            # Inject a new token for this event
            if self.P_Ready.tokens == 0:
                self.P_Ready.tokens = 1

            if state_val >= 1:
                self.T_Detect.fire()

            if state_val >= 2 and self.T_Notify.is_enabled():
                self.T_Notify.fire()

            if state_val >= 3 and self.T_Escalate.is_enabled():
                self.T_Escalate.fire()

            if state_val == 3 and self.T_Code.is_enabled():
                self.T_Code.fire()

            # Auto-complete when possible to free P_Active
            if self.T_Complete.is_enabled():
                self.T_Complete.fire()

            markings.append({p.name: p.tokens for p in self.places})

        return markings

    def check_resource_exhaustion(self, markings: List[Dict]) -> Dict:
        """
        Analyse markings for resource exhaustion.

        Returns
        -------
        dict with max_active_alerts, bounded, utilization, capacity
        """
        active_counts = [m.get("P_Active_Alerts", 0) for m in markings]
        max_active = max(active_counts) if active_counts else 0

        return {
            "max_active_alerts": int(max_active),
            "bounded": bool(max_active <= self.icu_capacity),
            "utilization": max_active / self.icu_capacity if self.icu_capacity > 0 else 0.0,
            "capacity": self.icu_capacity,
        }
